#!/usr/bin/env python3
"""Build the test corpus: hand-written PDFs, one per feature the parser has to handle.

Why hand-written rather than generated by a PDF library: a library emits whatever it
prefers, so the fixture exercises the library's taste rather than a named feature. Here
each file is assembled byte by byte, so `cmap.pdf` exists *because* subset fonts emit
glyph indices and `ascii85.pdf` exists *because* PDF filters chain. If a test fails you
know which construct broke.

The generator is the ground truth. It knows what text it drew and at which coordinates,
so it writes the `.expected.txt` beside each PDF itself -- the extractor never grades
its own homework. Standard library only (zlib, base64); no reportlab, no PDF toolkit.

    python tools/make_corpus.py          # regenerate tests/corpus/

Committed output is what CI checks, so running this should produce no git diff.
"""

import base64
import zlib
from pathlib import Path

CORPUS = Path(__file__).resolve().parent.parent / "tests" / "corpus"


# --------------------------------------------------------------------- PDF assembly
class Pdf:
    """Minimal PDF writer: numbered objects, a classic xref, nothing clever."""

    def __init__(self):
        self.objects = {}          # objnum -> bytes (body, without "N 0 obj"/"endobj")

    def add(self, num, body):
        if isinstance(body, str):
            body = body.encode("latin-1")
        self.objects[num] = body
        return num

    def stream(self, num, body, extra="", raw=False, ascii85=False):
        """A stream object. By default the body is Flate-compressed."""
        if isinstance(body, str):
            body = body.encode("latin-1")
        if raw:
            data, filt = body, ""
        elif ascii85:
            # filters chain, and they apply in order: ASCII85 first, then Flate
            data = base64.a85encode(zlib.compress(body)) + b"~>"
            filt = "/Filter [/ASCII85Decode /FlateDecode]"
        else:
            data, filt = zlib.compress(body), "/Filter /FlateDecode"
        head = f"<< /Length {len(data)} {filt} {extra} >>\nstream\n".encode("latin-1")
        return self.add(num, head + data + b"\nendstream")

    def build(self):
        out = bytearray(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")
        offsets = {}
        for num in sorted(self.objects):
            offsets[num] = len(out)
            out += f"{num} 0 obj\n".encode("latin-1")
            out += self.objects[num]
            out += b"\nendobj\n"
        xref_at = len(out)
        high = max(self.objects) + 1
        out += f"xref\n0 {high}\n".encode("latin-1")
        out += b"0000000000 65535 f \n"
        for num in range(1, high):
            off = offsets.get(num, 0)
            out += f"{off:010d} 00000 n \n".encode("latin-1")
        out += (
            f"trailer\n<< /Size {high} /Root 1 0 R >>\nstartxref\n{xref_at}\n%%EOF\n"
        ).encode("latin-1")
        return bytes(out)


def simple_doc(pages, fonts=None, extra_objects=None, stream_kw=None):
    """One catalog, one page tree, N pages each with its own content stream.

    `pages` is a list of content-stream strings. Page objects are numbered from 10 up
    and content streams from 11, two apart, so object numbers stay stable and readable
    in a hex dump.
    """
    pdf = Pdf()
    stream_kw = stream_kw or {}
    page_nums = [10 + 2 * i for i in range(len(pages))]
    kids = " ".join(f"{n} 0 R" for n in page_nums)
    pdf.add(1, f"<< /Type /Catalog /Pages 2 0 R >>")
    pdf.add(2, f"<< /Type /Pages /Kids [{kids}] /Count {len(pages)} >>")
    res = fonts or "<< /Font << /FA 5 0 R >> >>"
    for i, content in enumerate(pages):
        pn, cn = page_nums[i], page_nums[i] + 1
        pdf.add(
            pn,
            f"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] "
            f"/Resources {res} /Contents {cn} 0 R >>",
        )
        pdf.stream(cn, content, **stream_kw)
    for num, body in (extra_objects or {}).items():
        pdf.add(num, body)
    return pdf


def helvetica(num=5):
    return {num: "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>"}


def show(x, y, text, font="FA", size=12):
    """BT ... ET showing one literal string at an absolute position."""
    return f"BT /{font} {size} Tf 1 0 0 1 {x} {y} Tm ({text}) Tj ET\n"


def write(name, pdf, expected, note):
    data = pdf.build() if isinstance(pdf, Pdf) else pdf
    (CORPUS / f"{name}.pdf").write_bytes(data)
    lines = [f"# {note}", f"# generated by tools/make_corpus.py -- do not hand-edit"]
    # tab is the field separator here, so whitespace inside expected text is escaped;
    # tests/test_pdftext.cpp reverses exactly these two substitutions
    for page, text in expected:
        esc = text.replace("\\", "\\\\").replace("\t", "\\t")
        lines.append(f"p{page}\t{esc}")
    (CORPUS / f"{name}.expected.txt").write_text("\n".join(lines) + "\n", newline="\n")
    print(f"  {name}.pdf  {len(data):>6} bytes  {len(expected)} expected line(s)")


# --------------------------------------------------------------------- the fixtures
def fixture_plain():
    """An uncompressed content stream, and two fragments sharing one baseline.

    The uncompressed case matters because it takes the fallback path: nothing inflates,
    so the raw bytes are scanned only because they contain a text operator. The shared
    baseline proves reflow() joins fragments left-to-right rather than in paint order --
    note the content paints RIGHT before LEFT on purpose.
    """
    content = (
        show(72, 700, "Invoice 2026-0431")
        + show(400, 640, "RIGHT")          # painted first
        + show(72, 640, "LEFT")            # ...but should read second
        + show(72, 580, "Total due 1,284.00 USD")
    )
    pdf = simple_doc([content], extra_objects=helvetica(), stream_kw={"raw": True})
    return pdf, [
        (1, "Invoice 2026-0431"),
        (1, "LEFT RIGHT"),
        (1, "Total due 1,284.00 USD"),
    ], "uncompressed stream; two fragments on one baseline, painted out of order"


def fixture_flate():
    """The ordinary case: /FlateDecode, which is what almost every real PDF uses."""
    content = (
        show(72, 700, "Flate compressed content stream")
        + show(72, 660, "second line")
    )
    pdf = simple_doc([content], extra_objects=helvetica())
    return pdf, [
        (1, "Flate compressed content stream"),
        (1, "second line"),
    ], "/FlateDecode -- the common case"


def fixture_ascii85():
    """Filters chain. /Filter [/ASCII85Decode /FlateDecode] is what ReportLab writes.

    Inflating the bytes between stream/endstream directly returns garbage here; the
    ASCII85 layer has to come off first. This was a real defect, found by reading the
    output rather than trusting a successful run.
    """
    content = show(72, 700, "ASCII85 wrapping Flate") + show(72, 660, "chained filters")
    pdf = simple_doc([content], extra_objects=helvetica(), stream_kw={"ascii85": True})
    return pdf, [
        (1, "ASCII85 wrapping Flate"),
        (1, "chained filters"),
    ], "/Filter [/ASCII85Decode /FlateDecode] -- filters chain"


def fixture_cmap():
    """A subset font: the bytes in the string are glyph indices, not characters.

    This is the single most common reason a PDF "has no text". The content stream shows
    <0102030405>; read as WinAnsi that is control characters. The real text only exists
    in the font's /ToUnicode CMap, two object hops away:

        content: /FB 12 Tf      ->  /Font << /FB 7 0 R >>
        object 7: /ToUnicode 8 0 R
        object 8: the CMap stream, with bfchar and bfrange sections

    Both CMap section types are exercised: bfchar for the one-off mappings and bfrange
    for the contiguous run.
    """
    # codes 1..5 -> "WIDTH", via bfchar;  codes 0x20..0x24 -> "12.50" via bfrange
    content = (
        "BT /FB 12 Tf 1 0 0 1 72 700 Tm <0102030405> Tj ET\n"
        "BT /FB 12 Tf 1 0 0 1 72 660 Tm <2021222324> Tj ET\n"
    )
    cmap = """/CIDInit /ProcSet findresource begin
12 dict begin
begincmap
/CMapName /SubsetFB def
/CMapType 2 def
1 begincodespacerange
<00> <ff>
endcodespacerange
5 beginbfchar
<01> <0057>
<02> <0049>
<03> <0044>
<04> <0054>
<05> <0048>
endbfchar
1 beginbfrange
<20> <24> [<0031> <0032> <002E> <0035> <0030>]
endbfrange
endcmap
CMapName currentdict /CMap defineresource pop
end
end
"""
    pdf = simple_doc(
        [content],
        fonts="<< /Font << /FB 7 0 R >> >>",
        extra_objects={
            7: "<< /Type /Font /Subtype /TrueType /BaseFont /AAAAAA+Arial "
               "/FirstChar 1 /LastChar 5 /ToUnicode 8 0 R >>",
        },
    )
    pdf.stream(8, cmap)
    return pdf, [
        (1, "WIDTH"),
        (1, "12.50"),
    ], "subset font: glyph indices decoded through a /ToUnicode CMap (bfchar + bfrange)"


def fixture_multipage():
    """Three sheets in one file. Each fragment must come back with its own page number.

    Without page attribution a merged package silently flattens into one undifferentiated
    list -- which does not lose information noisily, it produces a plausible wrong answer.
    /Kids gives the authoritative order, so this fixture deliberately lists its pages in
    the object file order 10, 12, 14 and expects exactly that order back.
    """
    pages = [
        show(72, 700, f"Sheet {i} of 3") + show(72, 660, f"detail {chr(ord('A') + i - 1)}")
        for i in (1, 2, 3)
    ]
    pdf = simple_doc(pages, extra_objects=helvetica())
    expected = []
    for i in (1, 2, 3):
        expected.append((i, f"Sheet {i} of 3"))
        expected.append((i, f"detail {chr(ord('A') + i - 1)}"))
    return pdf, expected, "three pages via /Kids; every fragment attributed to its sheet"


def fixture_rotated():
    """Text painted inside a rotated transform: q / cm / BT ... ET / Q.

    The text matrix alone gives coordinates in the rotated local space, so a vertical
    dimension callout comes back at or near the origin -- or negative. The CTM and the
    q/Q stack have to be tracked to put the fragment back where it appears on the sheet.
    Expected positions are asserted by the test, not just the strings.
    """
    rot = "0.7071 0.7071 -0.7071 0.7071"
    content = (
        show(72, 700, "horizontal baseline")
        + f"q {rot} 300 400 cm\nBT /FA 12 Tf 1 0 0 1 0 0 Tm (rotated callout) Tj ET\nQ\n"
        + show(72, 100, "after the transform is popped")
    )
    pdf = simple_doc([content], extra_objects=helvetica())
    return pdf, [
        (1, "horizontal baseline"),
        (1, "rotated callout"),
        (1, "after the transform is popped"),
    ], "rotated text inside q/cm/Q -- position must land on the sheet, not at the origin"


def fixture_escapes():
    r"""String syntax: escapes, nesting, octal, and hex strings.

    A PDF literal can contain balanced parentheses unescaped, escaped ones, and \ddd
    octal for bytes outside ASCII. Hex strings are the other spelling of the same thing.
    Getting this wrong truncates text at the first stray bracket.
    """
    content = (
        "BT /FA 12 Tf 1 0 0 1 72 700 Tm (A\\(B\\) and (nested) too) Tj ET\n"
        "BT /FA 12 Tf 1 0 0 1 72 660 Tm (back\\\\slash and tab\\there) Tj ET\n"
        "BT /FA 12 Tf 1 0 0 1 72 620 Tm (octal \\101\\102\\103) Tj ET\n"
        "BT /FA 12 Tf 1 0 0 1 72 580 Tm <48657820737472696E67> Tj ET\n"
    )
    pdf = simple_doc([content], extra_objects=helvetica())
    return pdf, [
        (1, "A(B) and (nested) too"),
        (1, "back\\slash and tab\there"),
        (1, "octal ABC"),
        (1, "Hex string"),
    ], "literal string escapes, nested parens, octal bytes, and hex strings"


def fixture_form():
    """A label/value document -- the shape almost every extraction job actually has.

    Labels sit in one column and their values in another, on the same baseline. Nothing
    in the PDF says the two are related; the relationship is purely geometric, which is
    why `examples/fields.cpp` has to look it up by position. This fixture exists so that
    example has something honest to run on.
    """
    rows = [
        ("Invoice Number", "INV-2026-0431"),
        ("Invoice Date", "2026-10-09"),
        ("Purchase Order", "PO-88213"),
        ("Vendor", "Northline Fabrication"),
        ("Subtotal", "1,184.00"),
        ("Tax", "100.00"),
        ("Total Due", "1,284.00"),
    ]
    content = show(72, 740, "REMITTANCE ADVICE", size=16)
    y = 680
    for label, value in rows:
        content += show(72, y, label) + show(300, y, value)
        y -= 28
    pdf = simple_doc([content], extra_objects=helvetica())
    expected = [(1, "REMITTANCE ADVICE")]
    expected += [(1, f"{label} {value}") for label, value in rows]
    return pdf, expected, "label/value rows sharing a baseline -- geometry is the only link"


FIXTURES = [
    ("plain", fixture_plain),
    ("form", fixture_form),
    ("flate", fixture_flate),
    ("ascii85", fixture_ascii85),
    ("cmap", fixture_cmap),
    ("multipage", fixture_multipage),
    ("rotated", fixture_rotated),
    ("escapes", fixture_escapes),
]


def main():
    CORPUS.mkdir(parents=True, exist_ok=True)
    print(f"writing corpus to {CORPUS}")
    for name, fn in FIXTURES:
        pdf, expected, note = fn()
        write(name, pdf, expected, note)
    print(f"{len(FIXTURES)} fixtures written")


if __name__ == "__main__":
    main()
